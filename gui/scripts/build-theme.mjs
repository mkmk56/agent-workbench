/**
 * Generate the static Astryx brand theme stylesheet.
 *
 * Astryx can inject theme CSS at runtime, but that places a <style> tag in the
 * document and conflicts with the app's strict CSP. This script pre-compiles
 * the theme into a normal CSS file that the renderer imports.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { generateThemeCSS } from '@astryxdesign/core/theme';
import { createBrandTheme } from '../src/theme/brand-theme.mjs';

const theme = createBrandTheme();
const { prose, component } = generateThemeCSS(theme);

const outFile = fileURLToPath(new URL('../src/theme/brand.generated.css', import.meta.url));
const css = `/* @generated by scripts/build-theme.mjs — do not edit manually.
 * Source: src/theme/brand-theme.mjs
 * Astryx: @astryxdesign/core 0.7.15
 */

@layer reset, astryx-base, astryx-theme;

@layer reset {
${prose ?? ''}
}

@layer astryx-theme {
${component ?? ''}
}
`;

writeFileSync(outFile, css, 'utf8');
console.log(`[theme] wrote ${outFile} (${css.length} bytes)`);